import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import { compile, parseDrawing, spec } from "./compiler.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check"))
  throw new Error("Usage: bun run scripts/generate.ts [--check]");
const check = args.includes("--check");
const drawings = [];
for (const file of (await readdir(`${root}drawings`))
  .filter((f) => f.endsWith(".icon.json"))
  .sort()) {
  drawings.push(parseDrawing(JSON.parse(await readFile(`${root}drawings/${file}`, "utf8")), file));
}
if (!drawings.length) throw new Error("No icon drawings found");
const icons = compile(drawings);
const outputs = new Map<string, string>();
const header =
  "// Generated by bun run --filter @amends/icons generate. Edit drawings/, not this file.\n";
for (const icon of icons) {
  outputs.set(
    `src/generated/${icon.name}.tsx`,
    `${header}
import { IconSvg, type IconProps } from "../icon.tsx";
export function ${icon.exportName}(props: IconProps) {
  return <IconSvg {...props}><path d="${icon.path}"${icon.fill ? ' fill="currentColor"' : ""} /></IconSvg>;
}
`,
  );
  outputs.set(
    `svg/${icon.name}.svg`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${spec.stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="${icon.path}"${icon.fill ? ' fill="currentColor"' : ""}/></svg>\n`,
  );
}
outputs.set(
  "src/index.ts",
  `${header}
export { iconSizes, iconWeights, type IconProps, type IconSize, type IconWeight } from "./icon.tsx";
export type { IconName } from "./catalog.ts";
${icons.map((icon) => `export { ${icon.exportName} } from "./generated/${icon.name}.tsx";`).join("\n")}
`,
);
outputs.set(
  "src/catalog.ts",
  `${header}
// Metadata only. Kept outside the component entry point and free of component imports.
export const iconCatalog = ${JSON.stringify(
    icons.map(({ name, title, keywords, categories, exportName }) => ({
      name,
      title,
      keywords,
      categories,
      exportName,
    })),
    null,
    2,
  )} as const;
export type IconName = (typeof iconCatalog)[number]["name"];
`,
);

// Format in memory so --check verifies the exact committed bytes without writing.
for (const [file, content] of outputs) {
  if (!file.endsWith(".svg")) {
    const result = await format(file, content);
    if (result.errors.length)
      throw new Error(`Could not format ${file}: ${JSON.stringify(result.errors)}`);
    outputs.set(file, result.code);
  }
}
const stale: string[] = [];
for (const directory of ["src/generated", "svg"]) {
  let files: string[];
  try {
    files = await readdir(`${root}${directory}`);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    files = [];
  }
  for (const file of files)
    if (!outputs.has(`${directory}/${file}`)) stale.push(`${directory}/${file}`);
}
const changed: string[] = [];
for (const [file, content] of outputs) {
  let current: string | undefined;
  try {
    current = await readFile(`${root}${file}`, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  if (current !== content) changed.push(file);
}
if (check && (changed.length || stale.length)) {
  throw new Error(
    `Generated icons are out of date. Run bun run --filter @amends/icons generate.\n${[...changed, ...stale].join("\n")}`,
  );
}
if (!check) {
  for (const directory of ["src/generated", "svg"])
    await mkdir(`${root}${directory}`, { recursive: true });
  for (const file of changed) await writeFile(`${root}${file}`, outputs.get(file)!);
  for (const file of stale) await rm(`${root}${file}`);
}
console.log(
  `${check ? "Verified" : "Generated"} ${icons.length} icons, Solid exports, catalog, and SVGs.`,
);
