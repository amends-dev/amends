/**
 * One connected PostgreSQL database, which every module of the adapter runs its statements on: the
 * Drizzle instance and the Effect SQL client whose transactions both share, with the pool's notice
 * listener, writer queue, and read cap. `make` applies the schema baseline in `drizzle/` through a
 * client it is given, one process at a time; `layer` opens the pool and does the same. A host
 * acquires it once and shares it across every workspace's binding, the directory, the accounts,
 * and sign-in storage.
 *
 * @since 0.1.0
 */
import { PgClient } from "@effect/sql-pg";
import * as PgDrizzle from "drizzle-orm/effect-postgres";
import { migrate } from "drizzle-orm/effect-postgres/migrator";
import { Context, Effect, Layer } from "effect";
import { SqlClient } from "effect/sql";
import { fileURLToPath } from "node:url";
import * as PostgresNotices from "./PostgresNotices.ts";
import * as PostgresReads from "./PostgresReads.ts";
import * as PostgresTurns from "./PostgresTurns.ts";

/**
 * The directory of the schema baseline generated by `bun run generate`, which `make` applies.
 *
 * @category utils
 * @since 0.1.0
 */
export const migrationsFolder = fileURLToPath(new URL("../drizzle", import.meta.url));

/**
 * The Drizzle instance statements are written with, running through the Effect SQL client.
 *
 * @category models
 * @since 0.1.0
 */
export type DrizzleClient = Effect.Success<ReturnType<typeof PgDrizzle.makeWithDefaults>>;

/**
 * One connected database: the Drizzle instance for typed statements, and the
 * Effect client whose transaction service both share. Every Drizzle statement
 * runs through that client, so a transaction the journal opens on a reserved
 * connection carries the Drizzle statements inside it.
 *
 * @category services
 * @since 0.1.0
 */
export class PostgresDatabase extends Context.Service<
  PostgresDatabase,
  {
    /** Typed statements, written with Drizzle. */
    readonly db: DrizzleClient;
    /** The Effect client every statement runs through, and the transactions they share. */
    readonly sql: SqlClient.SqlClient;
    /** Append wakeups and relayed signals, from one listener for this pool. */
    readonly notices: PostgresNotices.PostgresNotices;
    /** Turns among this process's writers to one workspace or log, before they take a connection. */
    readonly turns: PostgresTurns.PostgresTurns;
    /** The cap on connections one workspace's statements outside its transactions use at once. */
    readonly reads: PostgresReads.PostgresReads;
  }
>()("@amends-dev/storage-postgresql/PostgresDatabase") {}

/**
 * Construct the database service over the caller's PostgreSQL client, applying pending
 * migrations one process at a time. Its notice listener holds one of the pool's connections while
 * readers wait.
 *
 * @category constructors
 * @since 0.1.0
 */
export const make = Effect.fn("PostgresDatabase.make")(function* () {
  const sql = yield* SqlClient.SqlClient;
  const db = yield* PgDrizzle.makeWithDefaults();
  // Processes starting together would otherwise race to create the schema. The first to take
  // the lock migrates; the others wait for its commit and then find nothing left to apply.
  yield* sql.withTransaction(
    Effect.andThen(
      sql`SELECT pg_advisory_xact_lock(hashtextextended('amends:migrate', 0))`,
      migrate(db, { migrationsFolder }),
    ),
  );
  const notices = yield* PostgresNotices.make();
  return PostgresDatabase.of({
    db,
    sql,
    notices,
    turns: PostgresTurns.make(),
    reads: PostgresReads.make(),
  });
});

/**
 * Connect a pool with the given configuration and bring the schema up to date.
 *
 * @category layers
 * @since 0.1.0
 */
export const layer = (config: PgClient.PgPoolConfig) =>
  Layer.effect(PostgresDatabase, make()).pipe(Layer.provideMerge(PgClient.layer(config)));
